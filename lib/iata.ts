function normalize(s: string): string {
  return s
    .toLowerCase()
    .split(",")[0]
    .trim()
    .replace(/[^a-z0-9 ]/g, "")
    .replace(/\s+/g, " ");
}

export function toCityCode(input: string): string | null {
  if (!input) return null;
  const norm = normalize(input);
  if (!norm) return null;
  // Direct match first.
  if (CITY_TO_CODE[norm]) return CITY_TO_CODE[norm];
  // Last token only (e.g. "from san francisco" → "francisco" — unlikely but
  // catches "London Heathrow" → "heathrow" doesn't help either; this is just
  // a small additional shot).
  return null;
}

export function toAirlineCode(input: string): string | null {
  if (!input) return null;
  const norm = normalize(input);
  if (!norm) return null;
  if (AIRLINE_TO_CODE[norm]) return AIRLINE_TO_CODE[norm];
  // Try stripping common suffixes like "airlines"
  const stripped = norm.replace(/\s*(airlines|airways|air|airline)\s*$/, "").trim();
  if (stripped !== norm && AIRLINE_TO_CODE[stripped]) return AIRLINE_TO_CODE[stripped];
  return null;
}
