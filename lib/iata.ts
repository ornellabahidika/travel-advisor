function normalize(s: string): string {
  return s
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9 ]/g, "")
    .replace(/\s+/g, " ");
}

export function toCityCode(input: string): string | null {
  if (!input) return null;
  const segments = input
    .split(",")
    .map((p) => normalize(p))
    .filter(Boolean);
  // Try city match against each comma-separated segment.
  for (const seg of segments) {
    if (CITY_TO_CODE[seg]) return CITY_TO_CODE[seg];
  }
  // Fall back: try country hub against each segment (countries usually
  // live in the LAST segment, so iterate in reverse).
  for (const seg of [...segments].reverse()) {
    if (COUNTRY_TO_HUB[seg]) return COUNTRY_TO_HUB[seg];
  }
  return null;
}

export function toAirlineCode(input: string): string | null {
  if (!input) return null;
  const norm = normalize(input.split(",")[0] ?? "");
  if (!norm) return null;
  if (AIRLINE_TO_CODE[norm]) return AIRLINE_TO_CODE[norm];
  const stripped = norm.replace(/\s*(airlines|airways|air|airline)\s*$/, "").trim();
  if (stripped !== norm && AIRLINE_TO_CODE[stripped]) return AIRLINE_TO_CODE[stripped];
  return null;
}
